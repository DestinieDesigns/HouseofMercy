create table public.ai_recommendations (
  id uuid primary key default gen_random_uuid(),
  workspace_id text not null references public.workspaces(id) on delete cascade,
  idea_id uuid, kind text not null, body jsonb not null,
  source_refs jsonb not null default '[]',        -- which authorized records informed it
  created_by uuid references public.app_users(id) on delete set null,
  created_at timestamptz not null default now(),
  unique (workspace_id, id),
  foreign key (workspace_id, idea_id) references public.content_ideas(workspace_id, id) on delete set null (idea_id)
);

-- ===== Row Level Security =====
-- RLS is enabled on every table. Browser roles have no grants and an explicit deny policy, so a
-- publishable key can never read or write data directly. Only the hom-api Edge Function (service
-- role, bypasses RLS) touches these tables, and it derives workspace_id from the validated session,
-- never from client input.
do $$
declare t text;
begin
  for t in select tablename from pg_tables where schemaname='public' loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on public.%I from anon, authenticated', t);
    execute format('create policy %I on public.%I as restrictive for all to anon, authenticated using (false) with check (false)', 'deny_browser_'||t, t);
  end loop;
end $$;
revoke all on sequence public.items_seq from anon, authenticated;

-- ===== Last-admin guards (atomic; service role only) =====
create function public.hom_active_admins(ws text) returns integer language sql stable as $$
  select count(*)::int from public.memberships m join public.app_users u on u.id=m.user_id
  where m.workspace_id=ws and m.role='Admin' and u.account_status<>'Suspended'
$$;

create function public.hom_set_role(ws text, uid uuid, new_role text) returns void language plpgsql as $$
declare cur text;
begin
  perform 1 from public.memberships where workspace_id=ws and role='Admin' for update;
  select role into cur from public.memberships where workspace_id=ws and user_id=uid;
  if cur is null then raise exception 'NOT_FOUND'; end if;
  if cur='Admin' and new_role<>'Admin' and public.hom_active_admins(ws)<=1 then raise exception 'LAST_ADMIN'; end if;
  update public.memberships set role=new_role where workspace_id=ws and user_id=uid;
end $$;

create function public.hom_set_status(ws text, uid uuid, new_status text) returns text language plpgsql as $$
declare cur_role text; cur_status text; pending boolean; result text;
begin
  perform 1 from public.memberships where workspace_id=ws and role='Admin' for update;
  select m.role, u.account_status, u.password_requires_change into cur_role, cur_status, pending
    from public.memberships m join public.app_users u on u.id=m.user_id where m.workspace_id=ws and u.id=uid;
  if cur_role is null then raise exception 'NOT_FOUND'; end if;
  if new_status='Suspended' and cur_status<>'Suspended' and cur_role='Admin' and public.hom_active_admins(ws)<=1 then raise exception 'LAST_ADMIN'; end if;
  result := case when new_status='Suspended' then 'Suspended' when pending then 'Pending Password Setup' else 'Active' end;
  update public.app_users set account_status=result where id=uid;
  if result='Suspended' then delete from public.sessions where user_id=uid; end if;
  return result;
end $$;

create function public.hom_remove_member(ws text, uid uuid) returns void language plpgsql as $$
declare cur text;
begin
  perform 1 from public.memberships where workspace_id=ws and role='Admin' for update;
  select role into cur from public.memberships where workspace_id=ws and user_id=uid;
  if cur is null then raise exception 'NOT_FOUND'; end if;
  if cur='Admin' and public.hom_active_admins(ws)<=1 then raise exception 'LAST_ADMIN'; end if;
  delete from public.memberships where workspace_id=ws and user_id=uid;
  update public.items set data = data || '{"assigneeId":"","assignee":""}'::jsonb
    where workspace_id=ws and data->>'assigneeId'=uid::text;
end $$;

revoke execute on all functions in schema public from public, anon, authenticated;
grant execute on all functions in schema public to service_role;

insert into public.workspaces(id, name) values ('house-of-mercy', 'House of Mercy') on conflict do nothing;
